/**
 * Writes same-page English redirects for incomplete non-English article locales.
 * Never points these URLs at the homepage.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { scanArticleLocales } from './article-locale-scan.mjs';

const { incomplete } = scanArticleLocales();
const redirects = {};
const problems = [];

for (const row of incomplete) {
  if (!row.from || !row.to || row.from === row.to || row.to === '/') {
    problems.push(`${row.pageId}/${row.locale}: missing same-page destination (${row.from} -> ${row.to})`);
    continue;
  }
  if (redirects[row.from] && redirects[row.from] !== row.to) {
    problems.push(`${row.from}: conflicting targets`);
    continue;
  }
  redirects[row.from] = row.to;
}

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const destination = join(process.cwd(), 'src/app/i18n/incomplete-locale-redirects.mjs');
const body = `/** Generated by scripts/generate-incomplete-redirects.mjs. Do not edit by hand. */\nexport const INCOMPLETE_LOCALE_REDIRECTS = ${JSON.stringify(redirects, null, 2)};\n`;
writeFileSync(destination, body);
console.log(`Wrote ${Object.keys(redirects).length} same-page incomplete-locale redirects`);
