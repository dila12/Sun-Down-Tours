import { readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const IMG_DIR = 'src/assets/img';
const OUT_FILE = 'src/app/utils/image-variants.generated.ts';

async function walk(dir, relPrefix = 'assets/img') {
  const entries = await readdir(dir, { withFileTypes: true });
  const variants = new Map();

  for (const entry of entries) {
    const full = join(dir, entry.name);
    const rel = `${relPrefix}/${entry.name}`.replace(/\\/g, '/');

    if (entry.isDirectory()) {
      const nested = await walk(full, rel);
      for (const [base, widths] of nested) {
        const existing = variants.get(base) ?? new Set();
        widths.forEach((w) => existing.add(w));
        variants.set(base, existing);
      }
      continue;
    }

    const match = entry.name.match(/^(.+)-(\d+)w\.webp$/i);
    if (!match) {
      continue;
    }

    const basePath = `${relPrefix}/${match[1]}.webp`.replace(/\\/g, '/');
    const width = Number.parseInt(match[2], 10);
    const existing = variants.get(basePath) ?? new Set();
    existing.add(width);
    variants.set(basePath, existing);
  }

  return variants;
}

function toTs(variants) {
  const sorted = [...variants.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([base, widths]) => {
      const list = [...widths].sort((a, b) => a - b).join(', ');
      return `  '${base}': [${list}],`;
    })
    .join('\n');

  return `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit manually.
export const IMAGE_VARIANTS: Record<string, readonly number[]> = {
${sorted}
};
`;
}

async function main() {
  const variants = await walk(IMG_DIR);
  await writeFile(OUT_FILE, toTs(variants), 'utf8');
  console.log(`Wrote ${variants.size} image variant entries to ${OUT_FILE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
