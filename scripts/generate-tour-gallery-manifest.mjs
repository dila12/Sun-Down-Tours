import { readdir, writeFile, mkdir, access } from 'node:fs/promises';
import { join, extname, basename } from 'node:path';
import { TOUR_GALLERIES } from './tour-gallery.config.mjs';

const IMG_ROOT = 'src/assets/img';
const DEDICATED_ROOT = join(IMG_ROOT, 'tour-galleries');
const OUT_FILE = 'src/app/sharedComponents/tour-gallery/tour-gallery-images.generated.ts';

const RASTER_RE = /\.(jpe?g|png)$/i;
const VARIANT_RE = /-\d+w\./i;
const EXT_PRIORITY = { '.jpg': 3, '.jpeg': 2, '.png': 1 };

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function naturalCompare(a, b) {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
}

/**
 * Collect unique stems → best raster path (prefer .jpg over .jpeg/.png).
 * Skips responsive -{n}w variants and WhatsApp junk filenames.
 */
async function collectFolderImages(absDir, relPrefix) {
  if (!(await exists(absDir))) return [];

  const entries = await readdir(absDir, { withFileTypes: true });
  const byStem = new Map();

  for (const entry of entries) {
    if (!entry.isFile()) continue;
    if (!RASTER_RE.test(entry.name) || VARIANT_RE.test(entry.name)) continue;
    if (/^whatsapp/i.test(entry.name)) continue;

    const ext = extname(entry.name).toLowerCase();
    const stem = basename(entry.name, extname(entry.name));
    const rel = `${relPrefix}/${entry.name}`.replace(/\\/g, '/');
    const prev = byStem.get(stem);
    const score = EXT_PRIORITY[ext] ?? 0;
    if (!prev || score > prev.score) {
      byStem.set(stem, { rel, score, stem });
    }
  }

  return [...byStem.values()].sort((a, b) => naturalCompare(a.stem, b.stem));
}

function filterImages(items, { include, match } = {}) {
  let list = items;
  if (Array.isArray(include) && include.length) {
    const order = new Map(include.map((stem, i) => [stem, i]));
    list = items
      .filter((item) => order.has(item.stem))
      .sort((a, b) => (order.get(a.stem) ?? 0) - (order.get(b.stem) ?? 0));
  }
  if (match) {
    const re = new RegExp(match);
    list = list.filter((item) => re.test(item.stem));
  }
  return list.map((item) => item.rel);
}

async function listDedicatedGalleries() {
  if (!(await exists(DEDICATED_ROOT))) return {};

  const entries = await readdir(DEDICATED_ROOT, { withFileTypes: true });
  const result = {};
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const id = entry.name;
    const abs = join(DEDICATED_ROOT, id);
    const items = await collectFolderImages(abs, `assets/img/tour-galleries/${id}`);
    if (items.length) {
      result[id] = items.map((i) => i.rel);
    }
  }
  return result;
}

function toTs(map) {
  const body = Object.keys(map)
    .sort(naturalCompare)
    .map((id) => {
      const paths = map[id].map((p) => `    '${p}',`).join('\n');
      return `  '${id}': [\n${paths}\n  ],`;
    })
    .join('\n');

  return `// AUTO-GENERATED by scripts/generate-tour-gallery-manifest.mjs — do not edit.
// Re-run: npm run generate-tour-gallery-manifest
// Prefer adding files under src/assets/img/tour-galleries/{galleryId}/
// or update scripts/tour-gallery.config.mjs for existing folders.

export const TOUR_GALLERY_IMAGES: Readonly<Record<string, readonly string[]>> = {
${body}
};

export function getTourGalleryImages(galleryId: string): readonly string[] {
  return TOUR_GALLERY_IMAGES[galleryId] ?? [];
}
`;
}

async function main() {
  const dedicated = await listDedicatedGalleries();
  const map = { ...dedicated };

  for (const [id, cfg] of Object.entries(TOUR_GALLERIES)) {
    // Dedicated folder wins when it has images.
    if (map[id]?.length) continue;

    const folder = cfg.folder?.replace(/^\/+|\/+$/g, '') ?? '';
    const abs = join(IMG_ROOT, folder);
    const relPrefix = `assets/img/${folder}`.replace(/\\/g, '/');
    const items = await collectFolderImages(abs, relPrefix);
    map[id] = filterImages(items, cfg);
  }

  await mkdir(join(OUT_FILE, '..'), { recursive: true });
  await writeFile(OUT_FILE, toTs(map), 'utf8');

  const counts = Object.entries(map)
    .map(([id, imgs]) => `  ${id}: ${imgs.length}`)
    .join('\n');
  console.log(`Wrote ${Object.keys(map).length} galleries to ${OUT_FILE}\n${counts}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
